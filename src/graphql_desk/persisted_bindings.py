"""Render importable ID-only bindings with operation result and variable types."""

import ast
import keyword
import unicodedata
from collections.abc import Sequence

from .config import SchemaConfig
from .fragments import FragmentIndex, IndexedDocument, SchemaContext
from .operation_types import render_indexed_operation_types
from .schema_types import render_schema_types
from .source_graph import DocumentIdentity, PersistedDeclaration

_HEADER = "# Generated by GraphQL Desk; persisted binding. Do not edit.\n"


class _PrivateNamePrefix(ast.NodeTransformer):
    def __init__(self, prefix: str) -> None:
        self.prefix = prefix

    def _rename(self, value: str) -> str:
        marker = "__graphql_desk_"
        return self.prefix + value[len(marker) :] if value.startswith(marker) else value

    def visit_Name(self, node: ast.Name) -> ast.Name:
        node.id = self._rename(node.id)
        return node

    def visit_alias(self, node: ast.alias) -> ast.alias:
        if node.asname is not None:
            node.asname = self._rename(node.asname)
        return node


def _defined_names(statement: ast.stmt) -> set[str]:
    targets: list[ast.expr] = []
    if isinstance(statement, ast.Assign):
        targets = statement.targets
    elif isinstance(statement, ast.AnnAssign):
        targets = [statement.target]
    names = {
        node.id
        for target in targets
        for node in ast.walk(target)
        if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Store)
    }
    if isinstance(statement, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
        names.add(statement.name)
    if isinstance(statement, (ast.Import, ast.ImportFrom)):
        names.update(
            alias.asname or alias.name.split(".")[0] for alias in statement.names
        )
    return {name for name in names if not name.startswith("__graphql_desk_")}


def render_persisted_bindings(
    schema: SchemaConfig,
    context: SchemaContext,
    declarations: Sequence[PersistedDeclaration],
    index: FragmentIndex,
    *,
    client_directives: tuple[str, ...] = (),
) -> tuple[str, str]:
    """Return a source-free runtime module and its precise .pyi companion."""
    if context.schema_name != schema.name:
        raise ValueError("Persisted schema context differs")
    documents = {
        DocumentIdentity(item.call.module, item.call.range): item
        for item in index.documents
        if item.schema_identity == (item.call.module.project, schema.name)
    }
    selected: list[tuple[PersistedDeclaration, IndexedDocument]] = []
    for declaration in sorted(
        declarations,
        key=lambda item: (
            item.module.project,
            item.module.module,
            item.module.uri,
            item.range.start,
        ),
    ):
        if declaration.schema_name != schema.name:
            continue
        if declaration.binding is None:
            continue
        binding = declaration.binding
        if (
            not binding.isidentifier()
            or keyword.iskeyword(binding)
            or unicodedata.normalize("NFKC", binding) != binding
            or binding.startswith("__")
        ):
            raise ValueError("Persisted binding needs a public Python identifier")
        document = documents.get(declaration.document)
        if document is None or document.selected_operation is None:
            raise ValueError("Persisted binding has no indexed operation")
        selected.append((declaration, document))

    names = [declaration.binding for declaration, _ in selected]
    if len(set(names)) != len(names):
        raise ValueError("Persisted bindings in one schema must have unique names")

    schema_types = render_schema_types(
        context.schema, scalars=schema.scalars, enums=schema.enums
    )
    stubs = [schema_types]
    defined_names = {
        name
        for statement in ast.parse(schema_types).body
        for name in _defined_names(statement)
    }
    seen_type_statements = {
        ast.dump(statement, include_attributes=False)
        for statement in ast.parse(schema_types).body
    }
    runtime = [
        _HEADER,
        "from graphql_desk import persisted_id as __graphql_desk_persisted_id\n\n",
    ]
    for number, (declaration, document) in enumerate(selected):
        assert declaration.binding is not None
        rendered = render_indexed_operation_types(
            context,
            document,
            name=declaration.binding,
            scalars=schema.scalars,
            enums=schema.enums,
            client_directives=client_directives,
            disable_masking=schema.disable_masking,
            fragment_index=index,
        )
        if not rendered.startswith(schema_types):
            raise ValueError(
                "Persisted operation declarations differ from schema types"
            )
        operation_types = ast.parse(rendered[len(schema_types) :])
        operation_types = _PrivateNamePrefix(
            f"__graphql_desk_persisted_{number}_"
        ).visit(operation_types)
        ast.fix_missing_locations(operation_types)
        for statement in operation_types.body:
            signature = ast.dump(statement, include_attributes=False)
            if signature not in seen_type_statements:
                seen_type_statements.add(signature)
                added_names = _defined_names(statement)
                if collision := defined_names.intersection(added_names):
                    raise ValueError(
                        "Persisted binding creates colliding declarations: "
                        + ", ".join(sorted(collision))
                    )
                defined_names.update(added_names)
                stubs.append(ast.unparse(statement) + "\n")
        if declaration.binding in defined_names:
            raise ValueError(
                "Persisted binding name collides with a generated type: "
                f"{declaration.binding!r}"
            )
        defined_names.add(declaration.binding)
        runtime.append(
            f"{declaration.binding} = __graphql_desk_persisted_id({declaration.id!r})\n"
        )

    stub = (
        _HEADER + "".join(stubs) + "\nfrom graphql_desk import PersistedDocument as "
        "__graphql_desk_PersistedDocument\n\n"
        + "\n".join(
            f"{declaration.binding}: __graphql_desk_PersistedDocument["
            f"{declaration.binding}Result, {declaration.binding}Variables]"
            for declaration, _ in selected
        )
        + ("\n" if selected else "")
        + "__all__ = "
        + repr(names)
        + "\n"
    )
    runtime.append("\n__all__ = " + repr(names) + "\n")
    return "".join(runtime), stub


def generated_header() -> str:
    """Return the ownership marker used to protect existing project files."""
    return _HEADER

"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { createOwnedAnalysisArtifacts } = require("../src/ownedAnalysisArtifacts");

function fixture(t) {
  const workspace = fs.mkdtempSync(path.join(os.tmpdir(), "graphql-desk-artifacts-"));
  const root = path.join(workspace, "stubs");
  fs.mkdirSync(root);
  fs.writeFileSync(path.join(root, "preexisting.txt"), "keep");
  const vscode = { Uri: { file: file => ({ scheme: "file", fsPath: file, toString: () => file }) }, workspace: {
    isTrusted: true, textDocuments: [], getWorkspaceFolder: () => ({ uri: { fsPath: workspace } }),
  } };
  t.after(() => fs.rmSync(workspace, { recursive: true, force: true }));
  const make = files => createOwnedAnalysisArtifacts(vscode, workspace, root, "graphql_desk_generated", files);
  return { workspace, root, vscode, make };
}

const original = [
  { relative_path: "graphql_desk_generated/default.pyi", text: "selected: str\n" },
  { relative_path: "graphql_desk_generated/default_ast.pyi", text: "class Exact: ...\n" },
];

test("publishes a multi-file stub generation, removes only obsolete owned files, and cleans up", async t => {
  const f = fixture(t);
  const handle = f.make(original);
  const base = path.join(f.root, "graphql_desk_generated");
  const old = fs.readFileSync(path.join(base, "default.pyi"));
  const oldFingerprints = original.map(file => fs.readFileSync(path.join(f.root, file.relative_path), "utf8").match(/analysis artifact ([a-f0-9]{64})/)[1]);
  assert.match(old.toString(), /^# Generated by GraphQL Desk;/);
  assert.equal(await handle.publish(original.map(file => ({ ...file, text: file.text.replace("str", "str | None") })), () => true), true);
  const updated = original.map(file => fs.readFileSync(path.join(f.root, file.relative_path), "utf8"));
  assert.match(updated[0], /str \| None/);
  const fingerprints = updated.map(text => text.match(/analysis artifact ([a-f0-9]{64})/)[1]);
  assert.notEqual(fingerprints[0], oldFingerprints[0]);
  assert.equal(fingerprints[1], oldFingerprints[1], "unchanged artifacts retain their stable fingerprint");
  const next = [
    { relative_path: "graphql_desk_generated/default.pyi", text: "selected: int\n" },
    { relative_path: "graphql_desk_generated/new_ast.pyi", text: "class Exact: ...\n" },
  ];
  assert.equal(await handle.publish(next, () => true), true);
  assert.equal(fs.existsSync(path.join(base, "default_ast.pyi")), false);
  assert.match(fs.readFileSync(path.join(base, "new_ast.pyi"), "utf8"), /class Exact/);
  await handle.cleanup();
  assert.deepEqual(fs.readdirSync(f.root), ["preexisting.txt"]);
  assert.equal(fs.readFileSync(path.join(f.root, "preexisting.txt"), "utf8"), "keep");
});

test("analysis artifact fingerprints are deterministic and content-sensitive", async t => {
  const first = fixture(t);
  first.make(original);
  const readFingerprint = f => fs.readFileSync(path.join(f.root, "graphql_desk_generated", "default.pyi"), "utf8").split("\n", 1)[0];
  const fingerprint = readFingerprint(first);
  assert.match(fingerprint, /^# Generated by GraphQL Desk; analysis artifact [a-f0-9]{64}$/);

  const reordered = fixture(t);
  reordered.make([...original].reverse());
  assert.equal(readFingerprint(reordered), fingerprint);

  const changed = fixture(t);
  changed.make(original.map(file => ({ ...file, text: file.text + "# changed\n" })));
  assert.notEqual(readFingerprint(changed), fingerprint);
});

test("rejects stale work, dirty aliases and foreign artifacts without overwriting them", async t => {
  const f = fixture(t);
  const handle = f.make(original);
  const file = path.join(f.root, "graphql_desk_generated", "default.pyi");
  const before = fs.readFileSync(file);
  assert.equal(await handle.publish(original, () => false), false);
  assert.deepEqual(fs.readFileSync(file), before);
  f.vscode.workspace.textDocuments.push({ uri: f.vscode.Uri.file(file), isDirty: true });
  await assert.rejects(handle.publish(original, () => true), /user edits/);
  f.vscode.workspace.textDocuments.length = 0;
  fs.writeFileSync(file, "user bytes");
  await assert.rejects(handle.cleanup(), /changed externally/);
  assert.equal(fs.readFileSync(file, "utf8"), "user bytes");
});

test("refuses existing packages and rolls back an interrupted multi-file update", async t => {
  const f = fixture(t);
  fs.mkdirSync(path.join(f.root, "graphql_desk_generated"));
  fs.writeFileSync(path.join(f.root, "graphql_desk_generated", "default.pyi"), "foreign");
  assert.throws(() => f.make(original), /EEXIST/);
  fs.rmSync(path.join(f.root, "graphql_desk_generated"), { recursive: true });
  const handle = f.make(original);
  const base = path.join(f.root, "graphql_desk_generated");
  const before = new Map(original.map(file => [file.relative_path, fs.readFileSync(path.join(f.root, ...file.relative_path.split("/")))]));
  const rename = fs.renameSync;
  let replacements = 0;
  fs.renameSync = (...args) => {
    if (++replacements === 2) throw new Error("injected rename failure");
    return rename(...args);
  };
  try { await assert.rejects(handle.publish(original.map(file => ({ ...file, text: "changed\n" })), () => true), /injected rename failure/); }
  finally { fs.renameSync = rename; }
  for (const [relativePath, bytes] of before) assert.deepEqual(fs.readFileSync(path.join(f.root, ...relativePath.split("/"))), bytes);
  assert.deepEqual(fs.readdirSync(base).sort(), ["default.pyi", "default_ast.pyi"]);
});


  assert.equal(await handle.publish([], () => true), true);
  assert.deepEqual(fs.readdirSync(f.root), ["preexisting.txt"]);
  assert.equal(fs.readFileSync(path.join(f.root, "preexisting.txt"), "utf8"), "keep");

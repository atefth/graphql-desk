"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { createOwnedAnalysisStub } = require("../src/ownedAnalysisStub");

function fixture(t) {
  const workspace = fs.mkdtempSync(path.join(os.tmpdir(), "graphql-desk-owned-"));
  const root = path.join(workspace, "stubs");
  fs.mkdirSync(root);
  fs.writeFileSync(path.join(root, "foreign.txt"), "keep");
  const vscode = { Uri: { file: file => ({ fsPath: file, toString: () => file }) }, workspace: {
    isTrusted: true, textDocuments: [], getWorkspaceFolder: () => ({ uri: { fsPath: workspace } }),
  } };
  t.after(() => fs.rmSync(workspace, { recursive: true, force: true }));
  return { workspace, root, vscode, create: (text = "selected: str\n") => createOwnedAnalysisStub(vscode, workspace, root, "generated", text) };
}

test("fresh owned stubs publish serially, reject stale work, and remove only their package", async t => {
  const f = fixture(t);
  f.vscode.workspace.getWorkspaceFolder = () => ({ uri: { fsPath: process.platform === "win32" ? f.workspace.toLowerCase() : f.workspace } });
  const handle = f.create();
  const original = fs.readFileSync(handle.uri.fsPath);
  assert.match(original.toString(), /^# Generated by GraphQL Desk; analysis session /);
  assert.equal(await handle.publish("selected: None\n", () => false), false);
  let checks = 0;
  assert.equal(await handle.publish("selected: None\n", () => ++checks === 1), false);
  assert.deepEqual(fs.readFileSync(handle.uri.fsPath), original);
  assert.equal(await handle.publish("selected: None\n", async () => true), false);
  const first = handle.publish("selected: None\n", () => true);
  const second = handle.publish("selected: int\n", () => true);
  assert.deepEqual(await Promise.all([first, second]), [true, true]);
  assert.match(fs.readFileSync(handle.uri.fsPath, "utf8"), /selected: int/);
  await handle.cleanup();
  await handle.cleanup();
  assert.deepEqual(fs.readdirSync(f.root), ["foreign.txt"]);
  assert.equal(fs.readFileSync(path.join(f.root, "foreign.txt"), "utf8"), "keep");
  assert.equal(await handle.publish("late", () => true), false);
});

test("existing packages, restart leftovers, escapes and untrusted roots are never adopted", async t => {
  const f = fixture(t);
  const handle = f.create();
  const saved = fs.readFileSync(handle.uri.fsPath);
  assert.throws(() => f.create(), /EEXIST/);
  delete require.cache[require.resolve("../src/ownedAnalysisStub")];
  assert.throws(() => require("../src/ownedAnalysisStub").createOwnedAnalysisStub(f.vscode, f.workspace, f.root, "generated", "restart"), /EEXIST/);
  for (const name of ["../escape", "a/b", "a.b", "", "C:\\escape"]) {
    assert.throws(() => createOwnedAnalysisStub(f.vscode, f.workspace, f.root, name, "text"), /Invalid analysis location/);
  }
  assert.throws(() => createOwnedAnalysisStub(f.vscode, f.workspace, f.workspace, "other", "text"), /inside/);
  f.vscode.workspace.isTrusted = false;
  await assert.rejects(handle.publish("text", () => true), /trusted/);
  await assert.rejects(handle.cleanup(), /trusted/);
  assert.deepEqual(fs.readFileSync(handle.uri.fsPath), saved);
});

test("dirty buffers and foreign disk mutations survive publication and cleanup", async t => {
  for (const mutation of ["dirty", "alias", "untitled", "bytes", "inode", "extra"]) {
    const f = fixture(t);
    const handle = f.create();
    const file = handle.uri.fsPath;
    if (mutation === "dirty") f.vscode.workspace.textDocuments.push({ uri: handle.uri, isDirty: true, version: 3, getText: () => "user" });
    if (mutation === "untitled") f.vscode.workspace.textDocuments.push({ uri: { scheme: "untitled", fsPath: file, toString: () => `untitled:${file}` }, isDirty: true });
    if (mutation === "alias") {
      const alias = path.join(f.root, "alias.pyi");
      fs.linkSync(file, alias);
      f.vscode.workspace.textDocuments.push({ uri: f.vscode.Uri.file(process.platform === "win32" ? alias.toUpperCase() : alias), isDirty: true });
    }
    if (mutation === "bytes") fs.writeFileSync(file, "foreign");
    if (mutation === "inode") { fs.renameSync(file, `${file}.previous`); fs.writeFileSync(file, fs.readFileSync(`${file}.previous`)); }
    if (mutation === "extra") fs.writeFileSync(path.join(path.dirname(file), "user.txt"), "foreign");
    const before = fs.readFileSync(file);
    if (mutation !== "extra") await assert.rejects(handle.publish("new", () => true), /preserved/);
    await assert.rejects(handle.cleanup(), /preserved/);
    assert.deepEqual(fs.readFileSync(file), before);
  }
});

test("symlink or replaced parents and artifact links are refused without touching their targets", async t => {
  const f = fixture(t);
  const outside = path.join(f.workspace, "outside");
  fs.mkdirSync(outside);
  const alias = path.join(f.workspace, "alias");
  fs.symlinkSync(f.root, alias, process.platform === "win32" ? "junction" : "dir");
  assert.throws(() => createOwnedAnalysisStub(f.vscode, f.workspace, alias, "generated", "text"), /symbolic link/);
  const handle = f.create();
  fs.renameSync(f.root, `${f.root}-old`);
  fs.symlinkSync(outside, f.root, process.platform === "win32" ? "junction" : "dir");
  await assert.rejects(handle.publish("text", () => true), /symbolic link|changed/);
  await assert.rejects(handle.cleanup(), /symbolic link|changed/);
  assert.deepEqual(fs.readdirSync(outside), []);
});

test("staging failures roll back and final callback mutations cannot overwrite foreign data", async t => {
  const f = fixture(t);
  const handle = f.create();
  const before = fs.readFileSync(handle.uri.fsPath);
  const rename = fs.renameSync;
  fs.renameSync = () => { throw new Error("injected replacement failure"); };
  try { await assert.rejects(handle.publish("new", () => true), /injected/); }
  finally { fs.renameSync = rename; }
  assert.deepEqual(fs.readFileSync(handle.uri.fsPath), before);
  assert.deepEqual(fs.readdirSync(path.dirname(handle.uri.fsPath)), ["__init__.pyi"]);
  let checks = 0;
  await assert.rejects(handle.publish("new", () => {
    if (++checks === 2) fs.writeFileSync(handle.uri.fsPath, "foreign");
    return true;
  }), /preserved/);
  assert.equal(fs.readFileSync(handle.uri.fsPath, "utf8"), "foreign");
  assert.deepEqual(fs.readdirSync(path.dirname(handle.uri.fsPath)), ["__init__.pyi"]);
  const tampered = fixture(t);
  const other = tampered.create();
  const otherBefore = fs.readFileSync(other.uri.fsPath);
  let stagedChecks = 0;
  let temporary;
  await assert.rejects(other.publish("new", () => {
    if (++stagedChecks === 2) {
      temporary = path.join(path.dirname(other.uri.fsPath), fs.readdirSync(path.dirname(other.uri.fsPath)).find(name => name.endsWith(".tmp")));
      fs.writeFileSync(temporary, "foreign staged bytes");
    }
    return true;
  }), /Staged.*preserved/);
  assert.deepEqual(fs.readFileSync(other.uri.fsPath), otherBefore);
  assert.equal(fs.readFileSync(temporary, "utf8"), "foreign staged bytes");
  const truncated = fixture(t);
  const truncatedHandle = truncated.create();
  let truncationChecks = 0;
  let truncatedTemporary;
  await assert.rejects(truncatedHandle.publish("new", () => {
    if (++truncationChecks === 2) {
      truncatedTemporary = path.join(path.dirname(truncatedHandle.uri.fsPath), fs.readdirSync(path.dirname(truncatedHandle.uri.fsPath)).find(name => name.endsWith(".tmp")));
      fs.truncateSync(truncatedTemporary, 3);
    }
    return true;
  }), /Staged.*preserved/);
  assert.equal(fs.readFileSync(truncatedTemporary, "utf8"), "# G");
});

test("partial initialization rolls back and teardown invalidates already queued publications", async t => {
  const f = fixture(t);
  assert.throws(() => f.create("x".repeat(2 * 1024 * 1024)), /Invalid analysis stub/);
  const write = fs.writeFileSync;
  fs.writeFileSync = () => { throw new Error("injected initial write failure"); };
  try { assert.throws(() => f.create(), /injected/); }
  finally { fs.writeFileSync = write; }
  assert.deepEqual(fs.readdirSync(f.root), ["foreign.txt"]);
  const handle = f.create();
  const pending = handle.publish("late", () => true);
  const cleanup = handle.cleanup();
  assert.equal(await pending, false);
  await cleanup;
  assert.deepEqual(fs.readdirSync(f.root), ["foreign.txt"]);
  for (const stage of ["initial", "publish"]) {
    const foreign = fixture(t);
    const owned = stage === "publish" ? foreign.create() : null;
    const saved = owned && fs.readFileSync(owned.uri.fsPath);
    const sync = fs.fsyncSync;
    let changed;
    fs.fsyncSync = () => {
      const directory = path.join(foreign.root, "generated");
      changed = path.join(directory, stage === "initial" ? "__init__.pyi" : fs.readdirSync(directory).find(name => name.endsWith(".tmp")));
      fs.writeFileSync(changed, "FOREIGN EDIT AFTER OWN WRITE");
      throw new Error("injected sync failure after foreign edit");
    };
    try {
      if (owned) await assert.rejects(owned.publish("new", () => true), /injected sync/);
      else assert.throws(() => foreign.create(), /injected sync/);
    } finally { fs.fsyncSync = sync; }
    assert.equal(fs.readFileSync(changed, "utf8"), "FOREIGN EDIT AFTER OWN WRITE");
    if (owned) assert.deepEqual(fs.readFileSync(owned.uri.fsPath), saved);
  }
});

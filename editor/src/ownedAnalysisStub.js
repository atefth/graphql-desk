"use strict";

const fs = require("node:fs");
const path = require("node:path");
const { randomUUID } = require("node:crypto");
const MAX_STUB_BYTES = 1024 * 1024;

function identity(file) {
  const stat = fs.lstatSync(file);
  if (stat.isSymbolicLink()) throw new Error("Analysis path is a symbolic link");
  return stat;
}

function same(first, second) { return first.dev === second.dev && first.ino === second.ino; }
function normalized(value) { return process.platform === "win32" ? path.resolve(value).toLowerCase() : path.resolve(value); }

function parents(directory) {
  const result = [];
  for (let current = directory;; current = path.dirname(current)) {
    const stat = identity(current);
    if (!stat.isDirectory()) throw new Error("Analysis parent is not a directory");
    result.push([current, stat]);
    if (path.dirname(current) === current) return result;
  }
}

// This creates a fresh analysis package; it never adopts saved or previous-session outputs.
function createOwnedAnalysisStub(vscode, workspaceRoot, stubRoot, moduleName, initialText) {
  if (!path.isAbsolute(workspaceRoot) || !path.isAbsolute(stubRoot) ||
      !/^[A-Za-z_][A-Za-z_0-9]*$/.test(moduleName)) throw new Error("Invalid analysis location");
  const workspace = path.resolve(workspaceRoot);
  const root = path.resolve(stubRoot);
  const relative = path.relative(workspace, root);
  if (!relative || relative === ".." || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative)) {
    throw new Error("Analysis root must be inside its workspace");
  }
  const ancestry = parents(root);
  const directory = path.join(root, moduleName);
  const file = path.join(directory, "__init__.pyi");
  const uri = vscode.Uri.file(file);
  const marker = `# Generated by GraphQL Desk; analysis session ${randomUUID()}\n`;
  function dirtyDocument(document, target) {
    if (!document.isDirty || (document.uri.scheme && !["file", "untitled"].includes(document.uri.scheme))) return false;
    if (document.uri.toString() === vscode.Uri.file(target).toString()) return true;
    if (!document.uri.fsPath) return false;
    if (normalized(document.uri.fsPath) === normalized(target)) return true;
    try { return same(fs.statSync(document.uri.fsPath), fs.statSync(target)); }
    catch { return false; }
  }
  function bytes(text) {
    if (typeof text !== "string" || Buffer.byteLength(text, "utf8") > MAX_STUB_BYTES) throw new Error("Invalid analysis stub text");
    return Buffer.from(marker + text, "utf8");
  }
  function environment(target = file) {
    if (!vscode.workspace.isTrusted) throw new Error("Analysis workspace is not trusted");
    const owner = vscode.workspace.getWorkspaceFolder(vscode.Uri.file(root));
    if (!owner || normalized(owner.uri.fsPath) !== normalized(workspace)) throw new Error("Analysis workspace ownership changed");
    for (const [parent, stat] of ancestry) {
      if (!same(stat, identity(parent))) throw new Error("Analysis parent changed");
    }
    if (vscode.workspace.textDocuments.some(document => dirtyDocument(document, file) || dirtyDocument(document, target))) {
      throw new Error("Analysis stub has user edits; preserved");
    }
  }
  let expected = bytes(initialText);
  environment();
  fs.mkdirSync(directory); // Exclusive: existing data and restart leftovers are never adopted.
  const directoryIdentity = identity(directory);
  function removable(target, stat, intended, partial = false) {
    try {
      environment(target);
      if (!same(directoryIdentity, identity(directory))) return false;
      const current = identity(target);
      const content = fs.readFileSync(target);
      return current.isFile() && same(stat, current) && (partial
        ? content.length <= intended.length && intended.subarray(0, content.length).equals(content)
        : content.equals(intended));
    } catch { return false; }
  }
  let fileIdentity;
  let initialized = false;
  try {
    const descriptor = fs.openSync(file, "wx");
    fileIdentity = fs.fstatSync(descriptor);
    try { fs.writeFileSync(descriptor, expected); initialized = true; fs.fsyncSync(descriptor); }
    finally { fs.closeSync(descriptor); }
  } catch (error) {
    // Partial own writes may be removed; foreign bytes and dirty buffers survive rollback.
    if (fileIdentity && removable(file, fileIdentity, expected, !initialized)) fs.unlinkSync(file);
    try {
      environment();
      if (same(directoryIdentity, identity(directory)) && fs.readdirSync(directory).length === 0) fs.rmdirSync(directory);
    } catch { /* Preserve an unverified directory. */ }
    throw error;
  }
  let closing = false;
  let stopped = false;
  let queue = Promise.resolve();
  function check() {
    environment();
    if (!same(directoryIdentity, identity(directory)) || !same(fileIdentity, identity(file)) ||
        !fs.readFileSync(file).equals(expected)) throw new Error("Analysis artifact changed externally; preserved");
  }
  function serialize(action) {
    const result = queue.then(action);
    queue = result.catch(() => {});
    return result;
  }
  return {
    uri,
    publish(text, isCurrent) {
      return serialize(() => {
        if (closing || stopped) return false;
        const next = bytes(text);
        check();
        if (isCurrent() !== true) return false;
        const temporary = path.join(directory, `.graphql-desk-${randomUUID()}.tmp`);
        let temporaryIdentity;
        let written = false;
        try {
          const descriptor = fs.openSync(temporary, "wx");
          temporaryIdentity = fs.fstatSync(descriptor);
          try { fs.writeFileSync(descriptor, next); written = true; fs.fsyncSync(descriptor); }
          finally { fs.closeSync(descriptor); }
          // No await between the final freshness/ownership checks and replacement.
          const current = isCurrent() === true;
          check();
          environment(temporary);
          const stagedIdentity = identity(temporary);
          if (!stagedIdentity.isFile() || !same(temporaryIdentity, stagedIdentity) || !fs.readFileSync(temporary).equals(next)) {
            throw new Error("Staged analysis artifact changed externally; preserved");
          }
          if (!current || closing) return false;
          fs.renameSync(temporary, file);
          expected = next;
          fileIdentity = temporaryIdentity;
          return true;
        } finally {
          if (temporaryIdentity && removable(temporary, temporaryIdentity, next, !written)) fs.unlinkSync(temporary);
        }
      });
    },
    cleanup() {
      closing = true;
      return serialize(() => {
        if (stopped) return;
        check();
        if (fs.readdirSync(directory).some(name => name !== "__init__.pyi")) throw new Error("Foreign analysis package entries; preserved");
        fs.unlinkSync(file);
        fs.rmdirSync(directory);
        stopped = true;
      });
    },
  };
}

module.exports = { createOwnedAnalysisStub };

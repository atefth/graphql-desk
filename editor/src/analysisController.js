"use strict";

const path = require("node:path");
const fs = require("node:fs");
const { createHash, randomUUID } = require("node:crypto");
const { createAnalysisWorker } = require("./analysisWorker");
const activationFailed = Symbol("python-extension-activation-failed");

const key = target => JSON.stringify([target.project, target.schema_name]);
const canonical = value => {
  let result;
  try { result = fs.realpathSync.native(value); } catch {
    // Unsaved paths still inherit existing parent junctions and Windows short-name expansion.
    const absolute = path.resolve(value);
    const parent = path.dirname(absolute);
    result = parent === absolute ? absolute : path.join(canonical(parent), path.basename(absolute));
  }
  return process.platform === "win32" ? result.toLowerCase() : result;
};
const inside = (root, value) => {
  const relative = path.relative(root, value);
  return relative === "" || (!path.isAbsolute(relative) && relative !== ".." && !relative.startsWith(`..${path.sep}`));
};
function isVerifiedArtifact(filename, selectedStubRoot) {
  if (!inside(selectedStubRoot, filename)) return false;
  let descriptor;
  try {
    descriptor = fs.openSync(filename, "r");
    const stat = fs.fstatSync(descriptor);
    if (!stat.isFile() || stat.size > 1024 * 1024 + 160) return false;
    const bytes = Buffer.alloc(stat.size);
    if (fs.readSync(descriptor, bytes, 0, bytes.length, 0) !== stat.size) return false;
    const content = bytes.toString("utf8");
    const match = /^# Generated by GraphQL Desk; analysis artifact ([a-f0-9]{64})\n([\s\S]*)$/.exec(content);
    if (!match) return false;
    const relative = path.relative(selectedStubRoot, filename).split(path.sep);
    for (let packageEnd = 1; packageEnd < relative.length; packageEnd += 1) {
      const generatedPackage = relative.slice(0, packageEnd).join(".");
      const relativePath = relative.slice(packageEnd).join("/");
      const fingerprint = createHash("sha256").update(JSON.stringify({ format: 1, generatedPackage, relativePath, text: match[2] })).digest("hex");
      if (fingerprint === match[1]) return true;
    }
    return false;
  } catch { return false; }
  finally { if (descriptor !== undefined) fs.closeSync(descriptor); }
}
function isVerifiedGenerationFile(filename, generationRoot) {
  if (!inside(generationRoot, filename)) return false;
  let descriptor;
  try {
    const manifestPath = path.join(generationRoot, "complete.json");
    const stat = fs.lstatSync(manifestPath);
    if (stat.isSymbolicLink() || !stat.isFile() || stat.size > 2 * 1024 * 1024) return false;
    const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
    if (manifest?.owner !== "graphql-desk-analysis-generation" || manifest.format !== 2 || !Array.isArray(manifest.files)) return false;
    const relative = path.relative(generationRoot, filename).split(path.sep).join("/");
    const entry = manifest.files.find(item => item?.path === relative);
    if (!entry || typeof entry.sha256 !== "string" || !/^[a-f0-9]{64}$/.test(entry.sha256)) return false;
    descriptor = fs.openSync(filename, "r");
    const fileStat = fs.fstatSync(descriptor);
    if (!fileStat.isFile() || fileStat.size > 4 * 1024 * 1024) return false;
    const bytes = Buffer.alloc(fileStat.size);
    return fs.readSync(descriptor, bytes, 0, bytes.length, 0) === fileStat.size &&
      createHash("sha256").update(bytes).digest("hex") === entry.sha256;
  } catch { return false; }
  finally { if (descriptor !== undefined) fs.closeSync(descriptor); }
}
function artifactRootFor(filename, selectedStubRoot) {
  const managedRoot = path.basename(path.dirname(selectedStubRoot)) === "generations"
    ? path.resolve(selectedStubRoot, "..", "..") : selectedStubRoot;
  if (!inside(managedRoot, filename)) return null;
  const relative = path.relative(managedRoot, filename).split(path.sep);
  if (relative[0] === "generations" && /^g-\d+-[0-9a-f-]{36}$/i.test(relative[1] ?? "")) {
    return path.join(managedRoot, relative[0], relative[1]);
  }
  return inside(selectedStubRoot, filename) ? selectedStubRoot : managedRoot;
}

/** Captures are finite capabilities; watchers only request earlier invalidation. */
function createAnalysisController(vscode, { workerFactory = createAnalysisWorker, environment = () => process.env, changed = () => {}, report = () => {}, status = () => {}, configurationDiagnostics = () => {} } = {}) {
  let disposed = false;
  let epoch = 0;
  const states = new Map();
  const subscriptions = [];
  const folderWatches = new Map();
  const folderWatchRoots = new Map();
  const ownedAnalysisPaths = new Set();
  const ownedAnalysisDirectories = new Set();
  const interpreters = new Map();
  let pythonApiPromise;
  let pythonEnvironments;
  const configuredPython = folder => vscode.workspace.getConfiguration("graphqlDesk", folder.uri).get("pythonPath", "");
  function stopPolling(state) {
    clearTimeout(state.pollTimer); state.pollTimer = null;
    state.pollPaused = true; state.pollAbort?.abort();
  }
  function dropState(root) {
    const state = states.get(root);
    if (state) {
      stopPolling(state); state.polls.clear();
      state.artifactsAbort?.abort();
      state.cached = null; state.worker.dispose();
      reconcileSchemaWatches(state, new Set()); states.delete(root);
    }
  }
  const selectedKey = selected => selected && typeof selected.id === "string" && selected.id && typeof selected.path === "string" && selected.path ? JSON.stringify([selected.id, selected.path]) : null;
  async function environments(ticket, skip) {
    check(ticket);
    if (!pythonApiPromise) {
      const extension = vscode.extensions?.getExtension("ms-python.python");
      if (!extension) { skip?.("python-extension-unavailable"); return null; }
      const activation = Promise.resolve().then(() => { check(ticket); return extension.activate(); });
      const pending = activation.catch(() => {
        if (pythonApiPromise === pending) pythonApiPromise = undefined;
        skip?.(!trusted() || epoch !== ticket ? "capture-invalidated" : "python-extension-activation-failed");
        return activationFailed;
      });
      pythonApiPromise = pending;
    }
    const api = await pythonApiPromise;
    check(ticket);
    if (api === activationFailed) return null;
    const current = api?.environments;
    if (!current || typeof current.getActiveEnvironmentPath !== "function" || typeof current.resolveEnvironment !== "function" || typeof current.onDidChangeActiveEnvironmentPath !== "function") { pythonApiPromise = null; skip?.("python-environment-api-unavailable"); return null; }
    if (!pythonEnvironments) {
      pythonEnvironments = current;
      subscriptions.push(current.onDidChangeActiveEnvironmentPath(event => {
        if (!trusted()) return;
        const resource = event.resource?.uri ?? event.resource;
        if (resource && (resource.scheme !== "file" || !path.isAbsolute(resource.fsPath))) return;
        const filename = resource && canonical(resource.fsPath);
        let affected = false;
        const folders = new Map((vscode.workspace.workspaceFolders ?? [])
          .filter(folder => folder.uri.scheme === "file")
          .map(folder => [canonical(folder.uri.fsPath), folder]));
        for (const [root, state] of states) folders.set(root, state.folder);
        for (const [root, entry] of interpreters) folders.set(root, entry.folder);
        for (const [root, folder] of folders) {
          if (configuredPython(folder) !== "" || (filename && !inside(root, filename) && !inside(filename, root))) continue;
          interpreters.delete(root); dropState(root); affected = true;
        }
        if (affected) changed();
      }));
    }
    return current;
  }
  async function selectedPython(folder, root, ticket, skip) {
    const api = await environments(ticket, skip);
    check(ticket);
    if (!api || configuredPython(folder) !== "") return null;
    const selected = api.getActiveEnvironmentPath(folder.uri);
    const key = selectedKey(selected);
    if (!key) { interpreters.delete(root); dropState(root); skip?.("python-interpreter-not-selected"); return null; }
    let entry = interpreters.get(root);
    if (entry?.key !== key) {
      dropState(root);
      entry = { key, folder, promise: Promise.resolve().then(() => {
        check(ticket);
        if (configuredPython(folder) !== "" || interpreters.get(root) !== entry) return undefined;
        return api.resolveEnvironment({ id: selected.id, path: selected.path });
      }) };
      interpreters.set(root, entry);
    }
    let resolved;
    try { resolved = await entry.promise; }
    catch (error) {
      if (interpreters.get(root) === entry) { interpreters.delete(root); dropState(root); }
      throw error;
    }
    check(ticket);
    if (configuredPython(folder) !== "" || interpreters.get(root) !== entry || selectedKey(api.getActiveEnvironmentPath(folder.uri)) !== key) {
      if (interpreters.get(root) === entry) { interpreters.delete(root); dropState(root); }
      return null;
    }
    const executable = resolved?.executable?.uri;
    if (!executable || executable.scheme !== "file" || !path.isAbsolute(executable.fsPath)) { interpreters.delete(root); dropState(root); skip?.("python-interpreter-invalid"); return null; }
    return executable.fsPath;
  }
  const trusted = () => {
    const allowed = !disposed && vscode.workspace.isTrusted === true;
    if (!allowed) status(null);
    if (!allowed) for (const state of states.values()) { stopPolling(state); state.cached = null; state.worker.invalidate(); }
    return allowed;
  };
  const localPath = document => {
    const uri = document.uri;
    if (!["file", "untitled"].includes(uri.scheme) || !path.isAbsolute(uri.fsPath)) return null;
    return canonical(uri.fsPath);
  };
  const watchesSchema = (state, filename) => [...state.watches.keys()].some(watched => canonical(watched) === filename);
  const isGraphqlDocument = filename => /\.(?:graphql|graphqls|gql)$/i.test(filename);
  async function stateFor(snapshot, skip) {
    const ticket = epoch;
    if (!trusted()) { skip?.("workspace-untrusted"); return null; }
    const uri = vscode.Uri.parse(snapshot.uri);
    if (uri.scheme !== "file" || !path.isAbsolute(uri.fsPath)) { skip?.("document-not-file-backed"); return null; }
    const filename = canonical(uri.fsPath);
    // Worker facts use real paths; lexical aliases must not hide a deeper owner.
    const owners = (vscode.workspace.workspaceFolders ?? [])
      .filter(item => item.uri.scheme === "file" && inside(canonical(item.uri.fsPath), filename))
      .sort((left, right) => canonical(right.uri.fsPath).length - canonical(left.uri.fsPath).length);
    const deepest = owners.filter(item => canonical(item.uri.fsPath) === (owners[0] && canonical(owners[0].uri.fsPath)));
    const folder = deepest.length === 1 ? deepest[0] : null;
    if (!folder || folder.uri.scheme !== "file") { skip?.("document-outside-workspace"); return null; }
    const root = canonical(folder.uri.fsPath);
    const setting = configuredPython(folder);
    let python = setting;
    if (setting === "") {
      try { python = await selectedPython(folder, root, ticket, skip); } catch { skip?.("python-environment-resolution-failed"); return null; }
    }
    if (!trusted() || epoch !== ticket || configuredPython(folder) !== setting) { skip?.("capture-invalidated"); return null; }
    if (python === null) return null;
    let state = states.get(root);
    if (typeof python !== "string" || !path.isAbsolute(python)) {
      dropState(root);
      skip?.("python-interpreter-invalid");
      return null;
    }
    if (state && (state.python !== python || state.setting !== setting)) { dropState(root); state = null; }
    if (!state) {
      state = { root, folder, python, setting, worker: workerFactory({ python, workspace: root, isTrusted: trusted }),
        running: false, pending: new Map(), cached: null, artifactsAbort: null, targets: [], credentials: new Map(), revisions: [], watches: new Map(),
        polls: new Map(), pollTimer: null, pollAbort: null, polling: false, pollPaused: false };
      states.set(root, state);
    }
    return state;
  }
  function invalidate(source, ranges) {
    if (disposed) return;
    epoch += 1;
    for (const state of states.values()) { stopPolling(state); state.artifactsAbort?.abort(); state.cached = null; if (!trusted()) state.worker.invalidate(); }
    const uri = typeof source === "string" ? source : source?.toString?.();
    changed(typeof uri === "string" && uri ? uri : null, Array.isArray(ranges) ? ranges : null);
  }
  function snapshot(document) {
    const filename = localPath(document);
    return { uri: filename ? vscode.Uri.file(filename).toString() : document.uri.toString(), version: document.version, text: document.getText() };
  }
  function mapSnapshot(value, bundle) {
    const parsed = vscode.Uri.parse(value.uri);
    if (parsed.scheme !== "file") return value;
    const matches = bundle.request.modules.filter(item => {
      const candidate = vscode.Uri.parse(item.uri);
      return candidate.scheme === "file" && canonical(candidate.fsPath) === canonical(parsed.fsPath);
    });
    return matches.length === 1 ? { ...value, uri: matches[0].uri } : value;
  }
  function resolveUri(uri) {
    const parsed = vscode.Uri.parse(uri);
    if (parsed.scheme !== "file") return parsed;
    const matches = vscode.workspace.textDocuments.filter(document => localPath(document) === canonical(parsed.fsPath));
    return matches.length === 1 ? matches[0].uri : parsed;
  }
  function captureSignature(captured, schemaPaths = []) {
    // Dirty status is irrelevant when the buffer still matches its on-disk input.
    const matchesDisk = buffer => {
      try { return fs.readFileSync(buffer.path, "utf8") === buffer.text; }
      catch { return false; }
    };
    const relevantPaths = new Set(captured.request.buffers.map(buffer => canonical(buffer.path)));
    const schemaPathSet = new Set(schemaPaths.map(canonical));
    const buffers = captured.request.buffers.filter(buffer => buffer.is_dirty && !matchesDisk(buffer));
    const documents = captured.request.documents.filter(document => document.is_dirty &&
      (relevantPaths.has(canonical(document.path)) || schemaPathSet.has(canonical(document.path))) &&
      !matchesDisk(captured.texts.get(document.id)));
    const schemaBuffers = [...captured.texts].filter(([, buffer]) => buffer.is_dirty && schemaPathSet.has(canonical(buffer.path)) &&
      !matchesDisk(buffer)).sort(([left], [right]) => left.localeCompare(right));
    return JSON.stringify([captured.request.workspace, captured.request.candidates, buffers,
      documents, captured.request.editor_fallback, [...schemaPathSet].sort(), schemaBuffers]);
  }
  function credential(state, target) {
    const values = Object.create(null);
    const source = environment();
    for (const name of target.environment_names) if (typeof source[name] === "string") values[name] = source[name];
    // Keep secret-derived fingerprints private; wire revisions are random capabilities.
    const fingerprint = createHash("sha256").update(JSON.stringify(values)).digest("hex");
    const previous = state.credentials.get(key(target));
    const revision = previous?.fingerprint === fingerprint ? previous.revision : randomUUID();
    state.credentials.set(key(target), { fingerprint, revision });
    return { values, revision };
  }
  function revisions(state) {
    return state.targets.map(target => ({ project: target.project, schema_name: target.schema_name, revision: credential(state, target).revision }));
  }
  async function capture(state) {
    const found = await vscode.workspace.findFiles(new vscode.RelativePattern(state.folder, "**/*.py"), null);
    const documents = vscode.workspace.textDocuments.filter(document => {
      const filename = localPath(document);
      return filename && (inside(state.root, filename) || isGraphqlDocument(filename));
    });
    const pythonConfig = vscode.workspace.getConfiguration("python", state.folder.uri);
    const inspection = pythonConfig.inspect?.("analysis.stubPath");
    const explicitlyConfigured = inspection && [inspection.globalValue, inspection.workspaceValue, inspection.workspaceFolderValue]
      .some(value => value !== undefined);
    const configuredStubPath = explicitlyConfigured ? pythonConfig.get("analysis.stubPath", "") : "";
    const selectedStubPath = typeof configuredStubPath === "string" ? configuredStubPath.trim() : "";
    const selectedStubRoot = path.resolve(state.root, selectedStubPath || (explicitlyConfigured ? "typings" : ".graphql-desk/typings"));
    let generatedRoot = inside(state.root, selectedStubRoot) ? selectedStubRoot : null;
    if (generatedRoot && path.basename(path.dirname(generatedRoot)) === "generations") {
      generatedRoot = path.resolve(generatedRoot, "..", "..");
    }
    const isGeneratedRuntime = filename => {
      if (ownedAnalysisPaths.has(filename)) return true;
      if (!generatedRoot || !inside(generatedRoot, filename)) return false;
      const artifactRoot = artifactRootFor(filename, generatedRoot);
      return artifactRoot !== null && isVerifiedArtifact(filename, artifactRoot);
    };
    // Runtime companions count as sources only if the file is not a GraphQL Desk artifact.
    const candidates = new Set(found.filter(uri => uri.scheme === "file").map(uri => canonical(uri.fsPath))
      .filter(filename => !isGeneratedRuntime(filename)));
    for (const document of documents) {
      const filename = localPath(document);
      // VS Code can retain a clean document after its backing file was renamed or deleted.
      if (filename.endsWith(".py") && inside(state.root, filename) &&
          (document.isDirty || document.uri.scheme === "untitled") && !isGeneratedRuntime(filename)) candidates.add(filename);
    }
    const allowed = new Set(candidates);
    for (const filename of candidates) {
      if (!inside(state.root, filename)) throw new Error("Source escapes workspace");
      let parent = path.dirname(filename);
      while (true) {
        allowed.add(canonical(path.join(parent, "pyproject.toml")));
        if (parent === state.root) break;
        const next = path.dirname(parent);
        if (next === parent) throw new Error("Source escapes workspace");
        parent = next;
      }
    }
    const inventory = documents.map(document => ({ id: document.uri.toString(), path: localPath(document), version: document.version, is_dirty: document.isDirty }));
    inventory.sort((a, b) => a.id.localeCompare(b.id));
    const buffers = documents.filter(document => allowed.has(localPath(document))).map(document => ({ path: localPath(document), version: document.version, text: document.getText(), is_dirty: document.isDirty }));
    buffers.sort((a, b) => a.path.localeCompare(b.path));
    const request = { workspace: state.root, candidates: [...candidates].sort(), buffers, documents: inventory,
      editor_fallback: vscode.workspace.getConfiguration("graphqlDesk", state.folder.uri).get("project", null) };
    const texts = new Map(documents.map(document => [document.uri.toString(), { path: localPath(document), version: document.version, text: document.getText(), is_dirty: document.isDirty }]));
    return { request, texts };
  }
  // Keep at most one pending action per operation kind; edit storms never build a promise queue.
  function enqueue(state, action, kind = "analyze", ticket = epoch) {
    if (state.running) {
      if (state.pending.has("refresh") && kind !== "refresh") return Promise.resolve(null);
      const existing = state.pending.get(kind);
      if (existing) { existing.action = action; existing.ticket = ticket; return existing.promise; }
      if (kind === "refresh") {
        for (const pending of state.pending.values()) pending.resolve(null);
        state.pending.clear();
      }
      let resolve;
      let reject;
      const promise = new Promise((yes, no) => { resolve = yes; reject = no; });
      state.pending.set(kind, { action, kind, ticket, promise, resolve, reject });
      return promise;
    }
    state.running = true;
    return Promise.resolve().then(() => ticket === epoch && trusted() && states.get(state.root) === state ? action() : null).finally(() => {
      state.running = false;
      const pending = state.pending.values().next().value;
      if (pending) {
        state.pending.delete(pending.kind);
        enqueue(state, pending.action, pending.kind, pending.ticket).then(pending.resolve, pending.reject);
      }
      schedulePolling(state);
    });
  }
  function reconcileSchemaWatches(state, filenames) {
    for (const [filename, handles] of state.watches) if (!filenames.has(filename)) {
      handles.forEach(handle => handle.dispose());
      state.watches.delete(filename);
    }
    for (const filename of filenames) if (!state.watches.has(filename)) {
      const watcher = vscode.workspace.createFileSystemWatcher(new vscode.RelativePattern(path.dirname(filename), path.basename(filename)));
      state.watches.set(filename, [watcher, watcher.onDidChange(invalidate), watcher.onDidCreate(invalidate), watcher.onDidDelete(invalidate)]);
    }
  }
  function check(ticket, token, state, signal) {
    if (!trusted() || epoch !== ticket || token?.isCancellationRequested || signal?.aborted || (state && states.get(state.root) !== state)) throw new Error("Superseded analysis");
  }
  function schedulePolling(state) {
    clearTimeout(state.pollTimer); state.pollTimer = null;
    if (disposed || states.get(state.root) !== state || state.pollPaused || state.polling || state.running || !state.polls.size) return;
    const next = [...state.polls.values()].sort((a, b) => a.due - b.due)[0];
    // Node converts overflowing delays into 1ms; long intervals need bounded chunks.
    state.pollTimer = setTimeout(async () => {
      state.pollTimer = null;
      if (!trusted() || states.get(state.root) !== state || state.pollPaused) return;
      if (Date.now() < next.due) { schedulePolling(state); return; }
      state.polling = true;
      const abort = new AbortController(); state.pollAbort = abort;
      let attempted = false;
      try {
        if (await stateFor({ uri: state.folder.uri.toString() }) !== state) {
          if (states.get(state.root) === state) dropState(state.root);
          return;
        }
        if (abort.signal.aborted) return;
        if (state.running) return;
        attempted = true;
        await enqueue(state, () => build(state, undefined, next.target, abort), "poll");
      } catch { state.cached = null; if (!abort.signal.aborted && trusted()) status("Schema unavailable"); }
      finally {
        if (attempted && state.polls.get(key(next.target)) === next) next.due = Date.now() + next.interval * 1000;
        state.pollAbort = null; state.polling = false;
        schedulePolling(state);
        if (attempted && !abort.signal.aborted && states.get(state.root) === state && trusted()) changed();
      }
    }, Math.min(2_147_483_647, Math.max(1, next.due - Date.now())));
    state.pollTimer.unref?.();
  }
  function reconcilePolling(state) {
    const targets = new Map(state.targets.filter(target => target.refresh_interval > 0).map(target => [key(target), target]));
    for (const identity of state.polls.keys()) if (!targets.has(identity)) state.polls.delete(identity);
    for (const [identity, target] of targets) {
      const previous = state.polls.get(identity);
      if (!previous || previous.interval !== target.refresh_interval) state.polls.set(identity,
        { target, interval: target.refresh_interval, due: Date.now() + target.refresh_interval * 1000 });
      else previous.target = target;
    }
    state.pollPaused = false;
    schedulePolling(state);
  }
  async function build(state, token, refreshTarget, pollAbort, stage = () => {}, operationAbort) {
    const ticket = epoch;
    stage("analysis-capture-failed");
    check(ticket, token, state, pollAbort?.signal);
    const captured = await capture(state);
    check(ticket, token, state, pollAbort?.signal);
    const wanted = revisions(state);
    const revisionSignature = JSON.stringify(wanted);
    if (!refreshTarget && state.cached && captureSignature(captured, state.cached.schemaPaths) === state.cached.signature &&
        state.cached.revisionSignature === revisionSignature) return state.cached;
    // shortcut: stale jobs finish without publishing to retain fetched schemas; refine if measured edit latency needs interruption.
    const abort = operationAbort ?? pollAbort ?? (refreshTarget ? new AbortController() : null);
    const cancellation = !operationAbort && abort ? token?.onCancellationRequested?.(() => abort.abort()) : undefined;
    const requestWorker = message => state.worker.request(message, abort ? { signal: abort.signal } : undefined);
    try {
      stage("worker-prepare-failed");
      const prepared = await requestWorker({ op: "prepare", ...captured.request, remote_revisions: wanted });
      check(ticket, token, state, abort?.signal);
      state.targets = prepared.remote_schemas;
      state.revisions = prepared.remote_revisions;
      const schema_buffers = prepared.required_buffers.map(id => {
        if (!captured.texts.has(id)) throw new Error("Missing schema buffer");
        return captured.texts.get(id);
      });
      const watchPaths = new Set(prepared.local_schemas.map(schema => schema.path));
      // Keep prior schema repair watches until every invalid project config is fixed.
      if (prepared.configuration_diagnostics.length) {
        for (const filename of state.watches.keys()) watchPaths.add(filename);
      }
      reconcileSchemaWatches(state, watchPaths);
      let identity = prepared.id;
      let refreshStatus;
      if (refreshTarget) {
        const target = state.targets.find(item => key(item) === key(refreshTarget));
        if (pollAbort) {
          reconcilePolling(state);
          const scheduled = target && state.polls.get(key(target));
          if (!scheduled || scheduled.interval !== refreshTarget.refresh_interval || Date.now() < scheduled.due) {
            state.cached = null; return null;
          }
        }
        if (!target) throw new Error("Remote target changed");
        const credentials = credential(state, target);
        const refreshed = await requestWorker({ op: "refresh", ...captured.request, id: identity, schema_buffers,
          project: target.project, schema_name: target.schema_name, credential_revision: credentials.revision, environment: credentials.values });
        check(ticket, token, state, abort?.signal);
        identity = refreshed.id;
        state.revisions = state.revisions.filter(item => key(item) !== key(target));
        state.revisions.push({ project: target.project, schema_name: target.schema_name, revision: credentials.revision });
        state.revisions.sort((a, b) => key(a).localeCompare(key(b)));
        refreshStatus = refreshed.status;
      }
      const request = { ...captured.request, id: identity, schema_buffers, remote_revisions: state.revisions };
      stage("worker-analyze-failed");
      const bundle = await requestWorker({ op: "analyze", ...request });
      stage("analysis-freshness-check-failed");
      check(ticket, token, state, abort?.signal);
      const latest = await capture(state);
      check(ticket, token, state, abort?.signal);
      const schemaPaths = prepared.local_schemas.map(schema => schema.path);
      if (captureSignature(latest, schemaPaths) !== captureSignature(captured, schemaPaths)) throw new Error("Capture changed");
      configurationDiagnostics(state.folder.uri.toString(), prepared.configuration_diagnostics);
      const latestRevisions = revisions(state);
      if (state.revisions.some(active => !latestRevisions.some(current => key(current) === key(active) && current.revision === active.revision))) throw new Error("Credentials changed during analysis");
      if (refreshStatus && !pollAbort) report(refreshStatus === "ready" ? "Schema refreshed." : "Schema refresh failed; this schema is unavailable for analysis.");
      // Bind newly discovered targets before computing the credential freshness key.
      const result = { bundle, request, ticket, preferences: prepared.project_preferences,
        schemaPaths, signature: captureSignature(captured, schemaPaths),
        revisionSignature: JSON.stringify(latestRevisions) };
      state.cached = result;
      reconcilePolling(state);
      return result;
    } finally { cancellation?.dispose(); }
  }
  async function analyze(value, token) {
    if (!trusted() || token?.isCancellationRequested) return null;
    const state = await stateFor(value);
    if (!state || token?.isCancellationRequested) return null;
    try {
      const result = await enqueue(state, () => build(state));
      if (token?.isCancellationRequested || !trusted() || states.get(state.root) !== state) return null;
      if (result) status(result.bundle.unavailable_schemas.length ? "Schema unavailable" : null);
      return result?.bundle ?? null;
    }
    catch { state.cached = null; if (trusted()) status("Analysis unavailable"); return null; }
  }
  async function isCurrent(bundle, value, token) {
    if (!trusted() || token?.isCancellationRequested) return false;
    const state = await stateFor(value);
    if (!state || token?.isCancellationRequested) return false;
    try {
      const current = await enqueue(state, async () => {
        const cached = state.cached;
        if (!cached || cached.bundle !== bundle) return false;
        check(cached.ticket, undefined, state);
        const latest = await capture(state);
        check(cached.ticket, undefined, state);
        if (captureSignature(latest, cached.schemaPaths) !== cached.signature || JSON.stringify(revisions(state)) !== cached.revisionSignature) { state.cached = null; return false; }
        const reply = await state.worker.request({ op: "current", ...cached.request });
        check(cached.ticket, undefined, state);
        const final = await capture(state);
        check(cached.ticket, undefined, state);
        const current = reply.current && captureSignature(final, cached.schemaPaths) === captureSignature(latest, cached.schemaPaths) &&
          JSON.stringify(revisions(state)) === cached.revisionSignature;
        if (!current) state.cached = null;
        return current;
      }, "current");
      return Boolean(current) && !token?.isCancellationRequested && trusted() && state.cached?.bundle === bundle;
    } catch { state.cached = null; return false; }
  }
  async function artifacts(value, token, onSkip = () => {}) {
    const skip = reason => { try { onSkip(reason); } catch { /* Diagnostics must not affect analysis. */ } };
    if (!trusted()) { skip("workspace-untrusted"); return null; }
    if (token?.isCancellationRequested) { skip("request-cancelled"); return null; }
    const state = await stateFor(value, skip);
    if (!state) return null;
    if (token?.isCancellationRequested) { skip("request-cancelled"); return null; }
    state.artifactsAbort?.abort();
    const abort = new AbortController();
    state.artifactsAbort = abort;
    const cancellation = token?.onCancellationRequested?.(() => abort.abort());
    let failureReason = "analysis-artifacts-failed";
    try {
      return await enqueue(state, async () => {
        const cached = state.cached ?? await build(state, token, undefined, undefined, reason => { failureReason = reason; }, abort);
        if (!cached) { skip("analysis-unavailable"); return null; }
        failureReason = "artifact-preflight-failed";
        check(cached.ticket, token, state);
        const latest = await capture(state);
        check(cached.ticket, token, state);
        if (captureSignature(latest, cached.schemaPaths) !== cached.signature || JSON.stringify(revisions(state)) !== cached.revisionSignature) {
          state.cached = null;
          skip("analysis-snapshot-stale"); return null;
        }
        failureReason = "worker-artifacts-failed";
        const reply = await state.worker.request({ op: "artifacts", ...cached.request }, { signal: abort.signal });
        check(cached.ticket, token, state);
        if (reply.current === false) { state.cached = null; skip("worker-artifacts-stale"); return null; }
        failureReason = "artifact-freshness-check-failed";
        const final = await capture(state);
        check(cached.ticket, token, state);
        if (captureSignature(final, cached.schemaPaths) !== cached.signature || JSON.stringify(revisions(state)) !== cached.revisionSignature) {
          state.cached = null;
          skip("analysis-snapshot-stale"); return null;
        }
        return { ...reply, isCurrent: () => trusted() && !token?.isCancellationRequested &&
          epoch === cached.ticket && states.get(state.root) === state &&
          state.cached?.signature === cached.signature && state.cached?.revisionSignature === cached.revisionSignature };
      }, "artifacts").finally(() => {
        cancellation?.dispose();
        if (state.artifactsAbort === abort) state.artifactsAbort = null;
      });
    } catch { state.cached = null; skip(failureReason); return null; }
  }
  async function quarantine({ workspace, projects, invalidated_owners, preserve_current = false } = {}) {
    if (!trusted() || typeof workspace !== "string" || !path.isAbsolute(workspace) ||
        !Array.isArray(projects) || !Array.isArray(invalidated_owners)) return null;
    const root = canonical(workspace);
    const state = states.get(root);
    if (!state) return null;
    if (!preserve_current) {
      state.artifactsAbort?.abort();
      state.cached = null;
      state.worker.invalidate();
    }
    const ticket = epoch;
    try {
      const reply = await enqueue(state, () => state.worker.request({
        op: "quarantine", id: randomUUID(), workspace: state.root, projects, invalidated_owners,
      }), "quarantine", ticket);
      return ticket === epoch && trusted() && states.get(root) === state ? reply : null;
    } catch { return null; }
  }
  async function refresh() {
    if (!trusted()) { report("Trust this workspace before refreshing a schema."); return; }
    const document = vscode.window.activeTextEditor?.document;
    const state = document && await stateFor(snapshot(document));
    if (!state) { report("Open a Python file and select a Python environment, or configure an absolute GraphQL Desk Python interpreter."); return; }
    const ticket = epoch;
    stopPolling(state);
    try {
      if (!await enqueue(state, () => build(state))) return;
      stopPolling(state);
      const choices = state.targets.map(target => ({ label: target.schema_name, description: target.project, target }));
      const choice = choices.length === 1 ? choices[0] : await vscode.window.showQuickPick(choices, { placeHolder: "Select a remote GraphQL schema to refresh" });
      if (!choice) { if (!choices.length) report("No remote schema is configured for this project."); return; }
      const run = token => enqueue(state, () => build(state, token, choice.target), "refresh");
      if (vscode.window.withProgress) await vscode.window.withProgress({ location: vscode.ProgressLocation.Notification,
        title: "Refreshing GraphQL schema", cancellable: true }, (_progress, token) => run(token));
      else await run();
      changed();
    } catch { report("GraphQL Desk could not refresh this schema. Check configuration and the selected interpreter."); }
    finally { if (epoch === ticket && states.get(state.root) === state && trusted()) reconcilePolling(state); }
  }
  function clientDirectives(bundle, call) {
    for (const state of states.values()) if (state.cached?.bundle === bundle) return state.cached.preferences.find(item => item.project === call.identity.module.project)?.client_directives ?? [];
    return [];
  }
  function reconcileFolderWatches() {
    const folders = new Map((vscode.workspace.workspaceFolders ?? [])
      .filter(folder => folder.uri.scheme === "file").map(folder => [folder.uri.toString(), folder]));
    for (const [uri, handles] of folderWatches) if (!folders.has(uri)) {
      handles.forEach(handle => handle.dispose());
      const root = folderWatchRoots.get(uri);
      if (root) {
        const remainingRoots = [...folders.values()].map(folder => canonical(folder.uri.fsPath));
        for (const filename of ownedAnalysisPaths) {
          if (inside(root, filename) && !remainingRoots.some(remaining => inside(remaining, filename))) ownedAnalysisPaths.delete(filename);
        }
        for (const directory of ownedAnalysisDirectories) {
          if (inside(root, directory) && !remainingRoots.some(remaining => inside(remaining, directory))) ownedAnalysisDirectories.delete(directory);
        }
      }
      folderWatchRoots.delete(uri);
      folderWatches.delete(uri);
    }
    for (const [uri, folder] of folders) if (!folderWatches.has(uri)) {
      const watcher = vscode.workspace.createFileSystemWatcher(new vscode.RelativePattern(folder, "**/*"));
      const sourceChanged = resource => {
        if (resource?.scheme === "file" && path.basename(resource.fsPath).toLowerCase() === "settings.json" &&
            path.basename(path.dirname(resource.fsPath)).toLowerCase() === ".vscode") return;
        if (resource?.scheme === "file") {
          const parts = path.resolve(resource.fsPath).split(path.sep);
          const lower = parts.map(part => part.toLowerCase());
          const marker = lower.lastIndexOf(".graphql-desk");
          const managedRoot = marker >= 0 && lower[marker + 1] === "typings" &&
            (marker + 2 === parts.length || lower[marker + 2] === "generations" && marker + 3 === parts.length);
          const generation = marker >= 0 && lower[marker + 1] === "typings" && lower[marker + 2] === "generations" &&
            /^g-\d+-[0-9a-f-]{36}$/i.test(parts[marker + 3] ?? "");
          const generationDirectory = generation && marker + 4 < parts.length;
          if (managedRoot || generation) {
            const filename = canonical(resource.fsPath);
            try {
              const stat = fs.lstatSync(resource.fsPath);
              if (stat.isDirectory() && !stat.isSymbolicLink() && (managedRoot || generationDirectory || marker + 4 === parts.length)) {
                ownedAnalysisDirectories.add(filename);
                return;
              }
            } catch (error) {
              if (error.code === "ENOENT" && ownedAnalysisDirectories.delete(filename)) return;
            }
            const name = path.basename(resource.fsPath).toLowerCase();
            if (generation && (name === "complete.json" || /^\.graphql-desk-[0-9a-f-]+\.tmp$/i.test(name))) {
              let descriptor;
              try {
                const stat = fs.lstatSync(resource.fsPath);
                if (stat.isSymbolicLink() || !stat.isFile() || stat.size > 2 * 1024 * 1024) throw new Error("Unverified generation control file");
                descriptor = fs.openSync(resource.fsPath, "r");
                const bytes = Buffer.alloc(stat.size);
                const size = fs.readSync(descriptor, bytes, 0, bytes.length, 0);
                if (size === stat.size && JSON.parse(bytes.toString("utf8")).owner === "graphql-desk-analysis-generation") {
                  ownedAnalysisPaths.add(filename);
                  return;
                }
              } catch (error) { if (error.code === "ENOENT" && ownedAnalysisPaths.delete(filename)) return; }
              finally { if (descriptor !== undefined) fs.closeSync(descriptor); }
            }
          }
        }
        // Pylance inputs include our generated stubs. Their writes must not invalidate the
        // capture that produced them, or publication recursively restarts analysis. VS Code
        // configuration changes are delivered separately by onDidChangeConfiguration.
        const extension = resource?.scheme === "file" ? path.extname(resource.fsPath).toLowerCase() : "";
        const stagedArtifact = extension === ".tmp" && path.basename(resource.fsPath).startsWith(".graphql-desk-");
        const filename = extension === ".pyi" || extension === ".py" || extension === ".typed" || stagedArtifact ? canonical(resource.fsPath) : null;
        if (extension === ".pyi" || extension === ".py" || extension === ".typed" || stagedArtifact) {
          const pythonConfig = vscode.workspace.getConfiguration("python", folder.uri);
          const inspection = pythonConfig.inspect?.("analysis.stubPath");
          const explicitlyConfigured = inspection && [inspection.globalValue, inspection.workspaceValue, inspection.workspaceFolderValue]
            .some(value => value !== undefined);
          const configuredPath = explicitlyConfigured ? pythonConfig.get("analysis.stubPath", "") : "";
          const selectedPath = typeof configuredPath === "string" ? configuredPath.trim() : "";
          const selectedRoot = path.resolve(canonical(folder.uri.fsPath), selectedPath || (explicitlyConfigured ? "typings" : ".graphql-desk/typings"));
          if (stagedArtifact && inside(selectedRoot, filename) && /^\.graphql-desk-[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}\.tmp$/i.test(path.basename(filename))) return;
          let descriptor;
          let missing = false;
          try {
            descriptor = fs.openSync(resource.fsPath, "r");
            const header = Buffer.alloc(96);
            const size = fs.readSync(descriptor, header, 0, header.length, 0);
            const marker = header.subarray(0, size).toString("utf8");
            const artifactRoot = artifactRootFor(filename, selectedRoot);
            if (marker.startsWith("# Generated by GraphQL Desk; analysis session ") ||
                artifactRoot !== null && (isVerifiedArtifact(filename, artifactRoot) ||
                  isVerifiedGenerationFile(filename, artifactRoot) || extension === ".typed" &&
                  marker === "partial\n" && ownedAnalysisDirectories.has(canonical(artifactRoot)))) {
              ownedAnalysisPaths.add(filename);
              return;
            }
          } catch (error) { missing = error.code === "ENOENT"; /* Deleted or inaccessible user stubs remain source changes. */ }
          finally { if (descriptor !== undefined) fs.closeSync(descriptor); }
          if (missing && filename && ownedAnalysisPaths.delete(filename)) return;
          if (filename) ownedAnalysisPaths.delete(filename);
        }
        invalidate(resource?.scheme === "file" ? resource : null);
      };
      const handles = [watcher, watcher.onDidChange(sourceChanged), watcher.onDidCreate(sourceChanged), watcher.onDidDelete(sourceChanged)];
      folderWatches.set(uri, handles);
      folderWatchRoots.set(uri, canonical(folder.uri.fsPath));
    }
  }
  const extensionSettingsDocument = document => {
    const uri = document?.uri;
    return uri?.scheme === "file" && path.basename(uri.fsPath).toLowerCase() === "settings.json" &&
      path.basename(path.dirname(uri.fsPath)).toLowerCase() === ".vscode";
  };
  for (const event of ["onDidOpenTextDocument", "onDidChangeTextDocument", "onDidCloseTextDocument", "onDidSaveTextDocument", "onDidChangeConfiguration", "onDidChangeWorkspaceFolders", "onDidGrantWorkspaceTrust"]) {
    if (vscode.workspace[event]) subscriptions.push(vscode.workspace[event](change => {
      const document = change?.document ?? (["onDidOpenTextDocument", "onDidCloseTextDocument", "onDidSaveTextDocument"].includes(event) ? change : null);
      if (event !== "onDidChangeConfiguration" && extensionSettingsDocument(document)) return;
      const filename = event !== "onDidChangeConfiguration" && document ? localPath(document) : null;
      if (document && event !== "onDidChangeConfiguration" && (!filename ||
          (!(vscode.workspace.workspaceFolders ?? []).some(folder => folder.uri.scheme === "file" &&
            inside(canonical(folder.uri.fsPath), filename)) &&
           ![...states.values()].some(state => watchesSchema(state, filename))))) return;
      if (event !== "onDidChangeConfiguration" && document?.uri?.scheme === "file" &&
          ownedAnalysisPaths.has(canonical(document.uri.fsPath)) && !(event === "onDidChangeTextDocument" && document.isDirty)) return;
      if (event === "onDidChangeConfiguration" && change?.affectsConfiguration &&
          !change.affectsConfiguration("graphqlDesk") &&
          !(change.affectsConfiguration("python") && !change.affectsConfiguration("python.analysis.stubPath"))) return;
      if (event === "onDidChangeConfiguration" && change?.affectsConfiguration?.("python.analysis.stubPath") &&
          !change.affectsConfiguration("graphqlDesk")) return;
      if (event === "onDidChangeConfiguration") {
        for (const [root, state] of states) {
          const python = vscode.workspace.getConfiguration("graphqlDesk", state.folder.uri).get("pythonPath", "");
          if (python !== state.setting) { interpreters.delete(root); dropState(root); }
        }
      }
      if (event === "onDidChangeWorkspaceFolders") {
        for (const root of states.keys()) dropState(root);
        interpreters.clear();
        reconcileFolderWatches();
      }
    if (event === "onDidChangeTextDocument" && Array.isArray(change?.contentChanges) && !change.contentChanges.length) return;
      const ranges = event === "onDidChangeTextDocument" && Array.isArray(change?.contentChanges)
        ? change.contentChanges.map(item => ({ start: item.rangeOffset, end: item.rangeOffset + item.rangeLength })) : null;
      invalidate(document?.uri ?? (change?.scheme === "file" ? change : null), ranges);
    }));
  }
  reconcileFolderWatches();
  return { analyze, isCurrent, artifacts, quarantine, isTrusted: trusted, snapshot, mapSnapshot, resolveUri, clientDirectives, refresh, invalidate,
    dispose() { disposed = true; epoch += 1; for (const root of states.keys()) dropState(root); interpreters.clear(); for (const handles of folderWatches.values()) handles.forEach(handle => handle.dispose()); folderWatches.clear(); folderWatchRoots.clear(); ownedAnalysisPaths.clear(); ownedAnalysisDirectories.clear(); subscriptions.forEach(item => item.dispose()); } };
}

"use strict";

const fs = require("node:fs");
const path = require("node:path");
const { createHash, randomUUID } = require("node:crypto");
const MAX_FILE_BYTES = 1024 * 1024;
const MAX_FILES = 4096;
async function replaceWithRetry(source, destination, validate) {
  for (let attempt = 0; ; attempt += 1) {
    validate();
    try { fs.renameSync(source, destination); return; }
    catch (error) {
      if (attempt === 3 || !["EPERM", "EACCES", "EBUSY"].includes(error.code)) throw error;
      await new Promise(resolve => setTimeout(resolve, 50 * (attempt + 1)));
    }
  }
}

const normalized = value => process.platform === "win32" ? path.resolve(value).toLowerCase() : path.resolve(value);
const same = (left, right) => left.dev === right.dev && left.ino === right.ino;
function renderOwnedAnalysisArtifact(generatedPackage, relativePath, text) {
  if (generatedPackage === "graphql_desk-stubs" && relativePath === "py.typed") return Buffer.from("partial\n", "utf8");
  const fingerprint = createHash("sha256").update(JSON.stringify({
    format: 1,
    generatedPackage,
    relativePath,
    text,
  })).digest("hex");
  return Buffer.from(`# Generated by GraphQL Desk; analysis artifact ${fingerprint}\n${text}`, "utf8");
}
function isOwnedAnalysisArtifact(bytes, generatedPackage, relativePath) {
  if (generatedPackage === "graphql_desk-stubs" && relativePath === "py.typed") return bytes.equals(Buffer.from("partial\n", "utf8"));
  const match = /^# Generated by GraphQL Desk; analysis artifact ([0-9a-f]{64})\n([\s\S]*)$/.exec(bytes.toString("utf8"));
  if (!match) return false;
  const fingerprint = createHash("sha256").update(JSON.stringify({
    format: 1, generatedPackage, relativePath, text: match[2],
  })).digest("hex");
  return match[1] === fingerprint;
}
function identity(file, options) {
  const stat = fs.lstatSync(file, options);
  if (stat.isSymbolicLink()) throw new Error("Analysis path is a symbolic link");
  return stat;
}
function packageParts(value) {
  if (value === "graphql_desk-stubs") return [value];
  return typeof value === "string" && value.split(".").every(part => /^[A-Za-z_][A-Za-z_0-9]*$/.test(part))
    ? value.split(".") : null;
}

function analysisPackageAbsent(root, generatedPackage) {
  const parts = packageParts(generatedPackage);
  if (!parts || !identity(root).isDirectory()) return false;
  let current = root;
  for (const part of parts) {
    current = path.join(current, part);
    try {
      if (!identity(current).isDirectory()) return false;
    } catch (error) {
      if (error.code === "ENOENT") return true;
      throw error;
    }
  }
  return false;
}
function artifactEntries(files, generatedPackage) {
  if (!Array.isArray(files) || files.length > MAX_FILES) throw new Error("Invalid analysis artifact set");
  if (files.length === 0) return new Map();
  const result = new Map();
  const prefix = `${generatedPackage.replaceAll(".", "/")}/`;
  let totalBytes = 0;
  for (const file of files) {
    const relativePath = typeof file?.relative_path === "string" && file.relative_path.startsWith(prefix)
      ? file.relative_path.slice(prefix.length) : "";
    const parts = relativePath.split("/");
    const bytes = typeof file.text === "string" ? Buffer.byteLength(file.text, "utf8") : MAX_FILE_BYTES + 1;
    if (!relativePath || generatedPackage === "graphql_desk-stubs" && !["__init__.pyi", "typed_document.pyi", "fragment_refs.pyi", "testing.pyi", "py.typed"].includes(relativePath) || parts.some((part, index) => index === parts.length - 1
      ? !(generatedPackage === "graphql_desk-stubs" && part === "py.typed") && !/^[A-Za-z_][A-Za-z_0-9]*\.pyi?$/.test(part)
      : !/^[A-Za-z_][A-Za-z_0-9]*$/.test(part)) ||
        bytes > MAX_FILE_BYTES || result.has(relativePath)) {
      throw new Error("Invalid analysis artifact");
    }
    totalBytes += bytes;
    if (totalBytes > 8 * MAX_FILE_BYTES) throw new Error("Invalid analysis artifact set");
    result.set(relativePath, file.text);
  }
  for (const relativePath of result.keys()) {
    if (relativePath.endsWith(".py") && !result.has(`${relativePath}i`)) {
      throw new Error("Runtime analysis artifact is missing its paired stub");
    }
  }
  return result;
}

function createOwnedAnalysisArtifacts(vscode, workspaceRoot, stubRoot, generatedPackage, files, stagingToken = null,
  { inMemoryManagedUpdates = false } = {}) {
  const packageNames = packageParts(generatedPackage);
  if (!packageNames || !path.isAbsolute(workspaceRoot) || !path.isAbsolute(stubRoot) ||
      stagingToken !== null && !/^[0-9a-f-]{36}$/.test(stagingToken)) throw new Error("Invalid analysis location");
  const workspace = path.resolve(workspaceRoot);
  const root = path.resolve(stubRoot);
  const relative = path.relative(workspace, root);
  if (!relative || relative === ".." || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative)) throw new Error("Analysis root must be inside its workspace");
  const ancestors = [];
  for (let current = root;; current = path.dirname(current)) {
    const stat = identity(current);
    if (!stat.isDirectory()) throw new Error("Analysis parent is not a directory");
    ancestors.push([current, stat]);
    if (path.dirname(current) === current) break;
  }
  const packageRoot = path.join(root, ...packageNames);
  const directoryStats = new Map();
  const artifacts = artifactEntries(files, generatedPackage);
  if (!artifacts.size) throw new Error("Invalid analysis artifact set");
  const expected = new Map();
  let cleaning = false;
  const dirty = target => vscode.workspace.textDocuments.some(document => {
    if (!document.isDirty || !["file", "untitled"].includes(document.uri.scheme)) return false;
    if (document.uri.toString() === vscode.Uri.file(target).toString()) return true;
    if (!document.uri.fsPath) return false;
    if (normalized(document.uri.fsPath) === normalized(target)) return true;
    try { return same(fs.statSync(document.uri.fsPath), fs.statSync(target)); } catch { return false; }
  });
  function environment() {
    if (!vscode.workspace.isTrusted) throw new Error("Analysis workspace is not trusted");
    const owner = vscode.workspace.getWorkspaceFolder(vscode.Uri.file(root));
    // Folder removal may retire verified session files, but cannot authorize publication or a new owner.
    if (owner ? normalized(owner.uri.fsPath) !== normalized(workspace) : !cleaning) throw new Error("Analysis workspace ownership changed");
    for (const [directory, stat] of ancestors) if (!same(stat, identity(directory))) throw new Error("Analysis parent changed");
  }
  function target(relativePath) { return path.join(packageRoot, ...relativePath.split("/")); }
  function directoriesFor(relativePath) {
    const result = [packageRoot];
    let directory = packageRoot;
    for (const part of relativePath.split("/").slice(0, -1)) {
      directory = path.join(directory, part.replace(/\.pyi$/, ""));
      result.push(directory);
    }
    return result;
  }
  function makeDirectories(relativePaths) {
    for (const relativePath of relativePaths) for (const directory of directoriesFor(relativePath)) {
      if (directoryStats.has(directory)) continue;
      checkDirectories();
      fs.mkdirSync(directory);
      directoryStats.set(directory, identity(directory));
    }
  }
  function checkDirectories() {
    environment();
    for (const [directory, stat] of directoryStats) if (!same(stat, identity(directory))) throw new Error("Analysis package changed externally; preserved");
  }
  function checkDirty(file) {
    if (dirty(file)) throw new Error("Analysis artifact has user edits; preserved");
  }
  function adoptExistingArtifacts() {
    if (!fs.existsSync(packageRoot)) return;
    const visit = (directory, prefix = "") => {
      const stat = identity(directory);
      if (!stat.isDirectory()) throw new Error("Analysis package changed externally; preserved");
      directoryStats.set(directory, stat);
      for (const name of fs.readdirSync(directory)) {
        const entry = path.join(directory, name);
        const child = identity(entry);
        if (child.isDirectory()) { visit(entry, prefix ? `${prefix}/${name}` : name); continue; }
        const relativePath = prefix ? `${prefix}/${name}` : name;
        const candidate = target(relativePath);
        checkDirty(candidate);
        const bytes = fs.readFileSync(candidate);
        const valid = artifactEntries([{ relative_path: `${generatedPackage.replaceAll(".", "/")}/${relativePath}`,
          text: relativePath === "py.typed" && generatedPackage === "graphql_desk-stubs" ? "partial\n" :
            bytes.toString("utf8").replace(/^# Generated by GraphQL Desk; analysis artifact [^\n]*\n/, "") }], generatedPackage);
        if (!valid.size || !isOwnedAnalysisArtifact(bytes, generatedPackage, relativePath)) {
          throw new Error("Unowned analysis package entries; preserved");
        }
        expected.set(relativePath, { bytes, identity: child });
      }
    };
    visit(packageRoot);
    const actual = [...expected.keys()].map(relativePath => {
      const bytes = expected.get(relativePath).bytes;
      return { relative_path: `${generatedPackage.replaceAll(".", "/")}/${relativePath}`,
        text: relativePath === "py.typed" && generatedPackage === "graphql_desk-stubs" ? "partial\n" :
          bytes.toString("utf8").replace(/^# Generated by GraphQL Desk; analysis artifact [^\n]*\n/, "") };
    });
    artifactEntries(actual, generatedPackage);
  }
  function checkOwned(file, record, partial = false, exactRead = false) {
    checkDirty(file);
    const stat = identity(file);
    if (!stat.isFile() || !same(record.identity, stat) ||
        (partial ? stat.size > record.bytes.length : stat.size !== record.bytes.length)) {
      throw new Error("Analysis artifact changed externally; preserved");
    }
    let bytes;
    if (exactRead) {
      const before = identity(file, { bigint: true });
      const unchanged = candidate => candidate.isFile() && same(before, candidate) &&
        candidate.size === before.size && candidate.mtimeNs === before.mtimeNs && candidate.ctimeNs === before.ctimeNs;
      if (!before.isFile() || Number(before.dev) !== stat.dev || Number(before.ino) !== stat.ino ||
          Number(before.size) !== stat.size) throw new Error("Analysis artifact changed externally; preserved");
      const descriptor = fs.openSync(file, "r");
      try {
        bytes = Buffer.allocUnsafe(stat.size);
        if (!unchanged(fs.fstatSync(descriptor, { bigint: true })) ||
            fs.readSync(descriptor, bytes, 0, bytes.length, 0) !== bytes.length ||
            !unchanged(fs.fstatSync(descriptor, { bigint: true })) || !unchanged(identity(file, { bigint: true }))) {
          throw new Error("Analysis artifact changed externally; preserved");
        }
      } finally { fs.closeSync(descriptor); }
    } else bytes = fs.readFileSync(file);
    if (!(partial
      ? bytes.length <= record.bytes.length && record.bytes.subarray(0, bytes.length).equals(bytes)
      : record.bytes.equals(bytes))) throw new Error("Analysis artifact changed externally; preserved");
  }
  function verify(extraFiles = new Set(), exactDirectories) {
    if (exactDirectories) {
      environment();
      for (const directory of exactDirectories) {
        const stat = directoryStats.get(directory);
        if (!stat || !same(stat, identity(directory))) throw new Error("Analysis package changed externally; preserved");
      }
      let parent = root;
      for (const part of packageNames.slice(0, -1)) {
        parent = path.join(parent, part);
        if (!identity(parent).isDirectory()) throw new Error("Analysis parent is not a directory");
      }
    } else checkDirectories();
    for (const [relativePath, record] of expected) {
      checkOwned(target(relativePath), record, false, Boolean(exactDirectories));
    }
    function visit(directory, prefix = "") {
      const entries = fs.opendirSync(directory);
      try {
        for (let item; (item = entries.readSync()); ) {
          const entry = path.join(directory, item.name);
          const relative = prefix ? `${prefix}/${item.name}` : item.name;
          if (identity(entry).isDirectory()) {
            if (exactDirectories && !exactDirectories.has(entry)) throw new Error("Foreign analysis package entries; preserved");
            visit(entry, relative);
          } else if (!expected.has(relative) && !extraFiles.has(relative)) {
            throw new Error("Foreign analysis package entries; preserved");
          }
        }
      } finally { entries.closeSync(); }
    }
    if (directoryStats.has(packageRoot)) visit(packageRoot);
  }
  function writeExclusive(file, bytes) {
    checkDirectories();
    checkDirty(file);
    const descriptor = fs.openSync(file, "wx");
    const stat = fs.fstatSync(descriptor);
    let written = false;
    try { fs.writeFileSync(descriptor, bytes); written = true; fs.fsyncSync(descriptor); }
    catch (error) {
      try {
        fs.closeSync(descriptor);
        checkDirectories();
        checkOwned(file, { bytes, identity: stat }, !written);
        fs.unlinkSync(file);
      } catch { /* Preserve bytes that are no longer verified as ours. */ }
      throw error;
    }
    finally { try { fs.closeSync(descriptor); } catch { /* Closed after a failed write. */ } }
    return stat;
  }
  async function updateOpenDocument(file, previous, next, isCurrent = () => true) {
    if (!inMemoryManagedUpdates || !file.endsWith(".pyi") || typeof vscode.workspace.openTextDocument !== "function" ||
        typeof vscode.workspace.applyEdit !== "function" || typeof vscode.WorkspaceEdit !== "function" ||
        typeof vscode.Range !== "function" || typeof vscode.Position !== "function") return null;
    checkDirectories();
    checkOwned(file, previous);
    checkDirty(file);
    const uri = vscode.Uri.file(file);
    const document = (vscode.workspace.textDocuments ?? []).find(item => item.uri?.scheme === "file" &&
      normalized(item.uri.fsPath) === normalized(file)) ?? await vscode.workspace.openTextDocument(uri);
    if (document.isDirty || !Buffer.from(document.getText(), "utf8").equals(previous.bytes)) {
      throw new Error("Managed typing buffer changed; preserved");
    }
    const version = document.version;
    const edit = new vscode.WorkspaceEdit();
    edit.replace(uri, new vscode.Range(new vscode.Position(0, 0), document.positionAt(document.getText().length)), next.toString("utf8"));
    if (isCurrent() !== true || await vscode.workspace.applyEdit(edit) !== true) throw new Error("Managed typing buffer update was rejected");
    const editedVersion = document.version;
    if (editedVersion <= version) throw new Error("Managed typing buffer version did not advance");
    if (isCurrent() !== true) {
      await restoreDocument(document, uri, previous.bytes, editedVersion);
      throw new Error("Superseded analysis");
    }
    if (document.version !== editedVersion || document.getText() !== next.toString("utf8")) {
      throw new Error("Managed typing buffer changed during update; preserved");
    }
    let saved = false;
    try { saved = await document.save(); }
    catch (error) { await restoreDocument(document, uri, previous.bytes, editedVersion); throw error; }
    if (!saved) {
      await restoreDocument(document, uri, previous.bytes, editedVersion);
      throw new Error("Managed typing buffer could not be saved");
    }
    if (document.isDirty || !fs.readFileSync(file).equals(next)) throw new Error("Managed typing buffer save was not verified");
    checkDirectories();
    return { bytes: next, identity: identity(file) };
  }
  async function restoreDocument(document, uri, bytes, expectedVersion) {
    if (!document.isDirty || document.version !== expectedVersion) return;
    const file = uri.fsPath;
    try {
      if (!fs.readFileSync(file).equals(bytes)) return;
    } catch { return; }
    const edit = new vscode.WorkspaceEdit();
    edit.replace(uri, new vscode.Range(new vscode.Position(0, 0), document.positionAt(document.getText().length)), bytes.toString("utf8"));
    if (await vscode.workspace.applyEdit(edit) && document.isDirty) await document.save();
  }
  function removeOwned(relativePath, record) {
    const file = target(relativePath);
    checkDirectories();
    checkOwned(file, record);
    fs.unlinkSync(file);
    expected.delete(relativePath);
  }
  function removeEmptyDirectories() {
    checkDirectories();
    for (const [directory, stat] of [...directoryStats].reverse()) {
      if (!same(stat, identity(directory))) throw new Error("Analysis package changed externally; preserved");
      if (fs.readdirSync(directory).length === 0) { fs.rmdirSync(directory); directoryStats.delete(directory); }
    }
  }

  environment();
  adoptExistingArtifacts();
  const adopted = new Map(expected);
  for (const relativePath of artifacts.keys()) checkDirty(target(relativePath));
  const initial = new Map();
  try {
    makeDirectories([...artifacts.keys()]);
    for (const [relativePath, text] of artifacts) {
      const bytes = renderOwnedAnalysisArtifact(generatedPackage, relativePath, text);
      const previous = expected.get(relativePath);
      if (previous?.bytes.equals(bytes)) continue;
      const token = stagingToken ? `${stagingToken}-${createHash("sha256").update(relativePath).digest("hex").slice(0, 16)}-` : "";
      const temporary = path.join(path.dirname(target(relativePath)), `.graphql-desk-${token}${randomUUID()}.tmp`);
      const stat = writeExclusive(temporary, bytes);
      initial.set(relativePath, { temporary, bytes, identity: stat, previous });
    }
    for (const [relativePath, stage] of initial) {
      const file = target(relativePath);
      checkDirectories();
      checkOwned(stage.temporary, stage);
      if (stage.previous) checkOwned(file, stage.previous);
      else if (fs.existsSync(file)) throw new Error("Foreign analysis artifact; preserved");
      checkDirectories();
      checkOwned(stage.temporary, stage);
      if (stage.previous) {
        checkOwned(file, stage.previous);
        fs.renameSync(stage.temporary, file);
      } else {
        if (fs.existsSync(file)) throw new Error("Foreign analysis artifact; preserved");
        fs.linkSync(stage.temporary, file);
        fs.unlinkSync(stage.temporary);
      }
      expected.set(relativePath, { bytes: stage.bytes, identity: identity(file) });
    }
    for (const [relativePath, record] of [...expected]) if (!artifacts.has(relativePath)) removeOwned(relativePath, record);
    verify();
  } catch (error) {
    for (const [relativePath, record] of [...expected]) if (!adopted.has(relativePath)) {
      try { removeOwned(relativePath, record); } catch { /* Preserve anything no longer verified as ours. */ }
    }
    for (const stage of initial.values()) {
      try { checkDirectories(); checkOwned(stage.temporary, stage); fs.unlinkSync(stage.temporary); } catch { /* Preserve unverified staging data. */ }
    }
    try { removeEmptyDirectories(); } catch { /* Preserve an unverified package. */ }
    throw error;
  }
  let stopped = false;
  let closing = false;
  let queue = Promise.resolve();
  const serialize = action => { const result = queue.then(action); queue = result.catch(() => {}); return result; };
  return {
    verifyExact(files) {
      if (closing || stopped) return false;
      const wanted = artifactEntries(files, generatedPackage);
      if (wanted.size !== expected.size) return false;
      if (!wanted.size) {
        environment();
        return analysisPackageAbsent(root, generatedPackage);
      }
      for (const [relativePath, text] of wanted) {
        if (!expected.get(relativePath)?.bytes.equals(renderOwnedAnalysisArtifact(generatedPackage, relativePath, text))) return false;
      }
      verify(undefined, new Set([...wanted.keys()].flatMap(directoriesFor)));
      return true;
    },
    publish(nextFiles, isCurrent) {
      return serialize(async () => {
        if (closing || stopped) return false;
        const next = artifactEntries(nextFiles, generatedPackage);
        verify();
        if (typeof isCurrent !== "function" || isCurrent() !== true) return false;
        for (const relativePath of next.keys()) checkDirty(target(relativePath));
        const staged = new Map();
        const updated = [];
        const removed = [];
        let changed = false;
        try {
          makeDirectories([...next.keys()]);
          for (const [relativePath, text] of next) {
            const bytes = renderOwnedAnalysisArtifact(generatedPackage, relativePath, text);
            if (expected.get(relativePath)?.bytes.equals(bytes)) continue;
            const file = target(relativePath);
            if (expected.has(relativePath)) {
              const previous = expected.get(relativePath);
              checkOwned(file, previous);
            } else if (fs.existsSync(file)) throw new Error("Foreign analysis artifact; preserved");
            const temporary = path.join(path.dirname(file), `.graphql-desk-${randomUUID()}.tmp`);
            const stat = writeExclusive(temporary, bytes);
            staged.set(relativePath, { temporary, bytes, identity: stat });
          }
          verify(new Set([...staged.values()].map(stage => path.relative(packageRoot, stage.temporary).split(path.sep).join("/"))));
          for (const [relativePath, stage] of staged) {
            const file = target(relativePath);
            const previous = expected.get(relativePath);
            const stagedPaths = new Set([...staged.values()].map(value => path.relative(packageRoot, value.temporary).split(path.sep).join("/")));
            let current;
            if (inMemoryManagedUpdates && previous && file.endsWith(".pyi")) {
              current = await updateOpenDocument(file, previous, stage.bytes, isCurrent);
            }
            if (!current) {
              await replaceWithRetry(stage.temporary, file, () => {
                if (isCurrent() !== true) throw new Error("Superseded analysis");
                verify(stagedPaths);
                checkDirty(file);
                checkOwned(stage.temporary, stage);
                if (previous) checkOwned(file, previous);
                else if (fs.existsSync(file)) throw new Error("Foreign analysis artifact; preserved");
              });
              current = { bytes: stage.bytes, identity: identity(file) };
            } else {
              checkDirectories();
              checkOwned(stage.temporary, stage);
              fs.unlinkSync(stage.temporary);
            }
            expected.set(relativePath, current);
            updated.push({ relativePath, previous, current });
            changed = true;
          }
          for (const [relativePath, previous] of [...expected]) if (!next.has(relativePath)) {
            if (isCurrent() !== true) throw new Error("Superseded analysis");
            verify();
            removeOwned(relativePath, previous);
            removed.push({ relativePath, previous });
            changed = true;
          }
          verify();
          return changed;
        } catch (error) {
          for (const { relativePath, previous, current } of updated.reverse()) {
            const file = target(relativePath);
            try {
              checkDirectories();
              checkOwned(file, current);
              if (!previous) { fs.unlinkSync(file); expected.delete(relativePath); }
              else {
                const temporary = path.join(path.dirname(file), `.graphql-desk-${randomUUID()}.tmp`);
                const identityValue = writeExclusive(temporary, previous.bytes);
                checkDirectories();
                checkOwned(file, current);
                checkOwned(temporary, { bytes: previous.bytes, identity: identityValue });
                try {
                  await replaceWithRetry(temporary, file, () => {
                    checkDirectories();
                    checkOwned(file, current);
                    checkOwned(temporary, { bytes: previous.bytes, identity: identityValue });
                  });
                } finally {
                  try { checkDirectories(); checkOwned(temporary, { bytes: previous.bytes, identity: identityValue }); fs.unlinkSync(temporary); }
                  catch { /* Preserve any temporary file that is no longer verified as ours. */ }
                }
                expected.set(relativePath, { bytes: previous.bytes, identity: identityValue });
              }
            } catch { /* Preserve bytes that are no longer verified as ours. */ }
          }
          for (const { relativePath, previous } of removed.reverse()) {
            const file = target(relativePath);
            try {
              if (fs.existsSync(file)) continue;
              const stat = writeExclusive(file, previous.bytes);
              expected.set(relativePath, { bytes: previous.bytes, identity: stat });
            } catch { /* Never replace an unowned artifact during rollback. */ }
          }
          throw error;
        } finally {
          for (const stage of staged.values()) {
            try { checkDirectories(); checkOwned(stage.temporary, stage); fs.unlinkSync(stage.temporary); } catch { /* Preserve unverified staging data. */ }
          }
          try { verify(); removeEmptyDirectories(); } catch { /* Preserve unverified package paths. */ }
        }
      });
    },
    cleanup() {
      closing = true;
      return serialize(() => {
        if (stopped) return;
        cleaning = true;
        try {
          verify();
          for (const [relativePath, record] of [...expected]) removeOwned(relativePath, record);
          removeEmptyDirectories();
          stopped = true;
        } finally { cleaning = false; }
      });
    },
  };
}

module.exports = { analysisPackageAbsent, createOwnedAnalysisArtifacts, renderOwnedAnalysisArtifact, isOwnedAnalysisArtifact };
